// 读取逐文件复核记录，找出合并上游后变动的文件；它只能检测内容变化，不能判断注释是否解释正确。
// 运行：node scripts/study-status.mjs；加 --files 列出整个项目逐文件的当前状态。
// 此脚本只读工作区，不自动标记完成、不改注释、不执行 Git 合并。

// 内置模块通过 node: 前缀导入，避免与同名第三方包混淆。
import { execFileSync } from "node:child_process";
// SHA-256 将文件全部字节映射为固定长度摘要；空格/注释变化也会触发复核提醒。
import { createHash } from "node:crypto";
// 同步读取适用于这个短命令行检查器；它不处于模型请求的实时热路径。
import { existsSync, readFileSync } from "node:fs";
// extname 取扩展名，join/resolve 组合跨平台路径。
import { basename, extname, join, resolve } from "node:path";
// import.meta.url 是当前 ESM 文件的 URL，转换后可得到不依赖调用者 cwd 的仓库根路径。
import { fileURLToPath } from "node:url";

// 从 scripts/ 返回一层就是仓库根目录，路径带空格也由 URL 工具处理。
const root = resolve(fileURLToPath(new URL("../", import.meta.url)));
// 记录只包含真正复核过的文件；未列出的新文件也会由下面的 Git 清单自动发现。
const coverage = JSON.parse(readFileSync(join(root, "docs/learning/pi/study-coverage.json"), "utf8"));
// 这份 JSON 可以手工编辑，是本脚本的输入边界；只接受已经复核过的三种声明，避免拼错后漏计。
const reviewStatuses = new Set(["complete", "partial", "reference"]);
// Object.entries 逐条取出文件路径与复核记录，错误信息指出具体记录。
for (const [path, review] of Object.entries(coverage.files)) {
	// 可选链让空记录也进入明确的无效状态错误；这里不从源码内容推断完成程度。
	if (!reviewStatuses.has(review?.status)) throw new Error(`Invalid review status for ${path}: ${review?.status}`);
	// SHA-256 是 256 位，即 64 个十六进制字符；缺失或误粘贴其他文字应报错，不当成有效快照。
	if (!/^[a-f0-9]{64}$/u.test(review.sha256)) throw new Error(`Invalid SHA-256 for ${path}`);
}
// Set 提供不重复的成员集合，用 has 判断某类代码/配置是否属于覆盖范围。
const extensions = new Set([
	".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".rs", ".py", ".sh", ".bash", ".ps1",
	".go", ".c", ".h", ".cc", ".cpp", ".cxx", ".hpp", ".m", ".mm", ".swift", ".bat", ".cmd",
	".css", ".html", ".sql", ".nix", ".toml", ".yaml", ".yml", ".json", ".jsonc", ".dockerignore",
]);
// Dockerfile、Git/包管理配置及 Git hook 没有普通源码扩展名，也属于需要理解的构建/配置入口。
const sourceNames = new Set(["Dockerfile", ".gitignore", ".gitattributes", ".npmrc", ".nvmrc", ".dockerignore", "Makefile", "Justfile", "Brewfile"]);
// 分开传递程序与参数，不经 shell 解释，路径中即使有特殊字符也不会变成命令。
const paths = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
	// 无论在哪里运行脚本，都查询当前仓库的文件。
	cwd: root,
	// 输出按 UTF-8 解码；-z 让文件名之间用空字符分隔，避免换行文件名造成歧义。
	encoding: "utf8",
})
	// Git 输出最后也有分隔符；filter(Boolean) 去掉末尾产生的空字符串。
	.split("\0")
	.filter(Boolean);

// 去重是因为新文件暂存后，在不同 Git 输出组合中不应重复计算同一文件。
const entries = [...new Set(paths)].sort().flatMap((path) => {
	// 学习文档的机器清单不是产品代码；锁文件记录解析结果，不能加注释破坏其格式。
	if (path.startsWith("docs/learning/pi/") || path.includes("/install-lock/") || path.endsWith("lock.json")) return [];
	// 不在代码/配置扩展集合中的图片、字体、Markdown 等不计算为源码文件。
	if (!extensions.has(extname(path)) && !sourceNames.has(basename(path)) && !path.startsWith(".husky/")) return [];
	// 已在工作区删除、尚未提交删除的文件可能仍出现在 Git 索引中，留到后面统一报告旧记录。
	if (!existsSync(join(root, path))) return [];
	// 只读取 Git 列出的文件，不遍历 node_modules、dist 或模型数据等已忽略产物。
	const bytes = readFileSync(join(root, path));
	// Buffer 保存原字节，只有查看文件头时才按 UTF-8 解码，指纹不依赖解码是否损失字符。
	const source = bytes.toString("utf8");
	// 每个文件的字节指纹独立计算，某个文件变更不会让其他文件被误标为变化。
	const sha256 = createHash("sha256").update(bytes).digest("hex");
	// 生成标识只看文件头；正文恰好讨论 generated 并不代表整个文件是产物。
	const header = source.split("\n").slice(0, 12).join("\n");
	// 显式生成文件、版本同步文件、第三方 vendor 文件要追其来源，不手写覆盖产物。
	const reference = /(?:\.generated\.|\.models\.ts$|\/vendor\/)/u.test(path) ||
		/@generated|auto-generated|automatically generated|do not edit|generated by/iu.test(header) ||
		path === "packages/ai/src/utils/version.ts";
	// 读取人的复核声明；不会用中文注释的数量自动把文件判为完整。
	const review = coverage.files[path];
	// 既有记录与当前字节不一致时优先标 stale；即使只是格式变化，也值得人工确认一次。
	const status = review && review.sha256 !== sha256 ? "stale" : review?.status ?? (reference ? "reference" : "pending");
	// flatMap 返回一项数组保留该文件；上面的空数组用于跳过文件。
	return [{ path, status, previousStatus: review?.status, note: review?.note ?? "" }];
});

// 即使上游把文件删除/改名并提交了，旧复核记录也必须被发现，不能悄悄从统计里消失。
const present = new Set(entries.map((entry) => entry.path));
// 逐个核对已有记录，而不是只看当前存在的源码路径。
for (const [path, review] of Object.entries(coverage.files)) {
	// 找不到当前文件时要求更新来源或移除已经失效的复核声明。
	if (!present.has(path)) entries.push({ path, status: "stale", previousStatus: review.status, note: "文件已移除、改名或离开源码范围；复核记录待更新" });
}

// 这几个标签是覆盖状态，不代表代码质量评分或 TypeScript 类型。
const labels = { complete: "完整注释", partial: "部分注释", pending: "待处理", stale: "需要复核", reference: "追溯生成/第三方来源" };
// process.argv 前两项是 Node 与脚本路径；后续参数才是用户传入选项。
const showFiles = process.argv.slice(2).includes("--files");
// 显示所有状态，计数为零也保留，方便观察合并上游前后的变化。
console.log(`源码与配置文件：${entries.length}；复核基线：${coverage.baselineCommit}`);
// Object.entries 把对象变成 [键,值] 对的数组，for...of 再逐对解构。
for (const [status, label] of Object.entries(labels)) {
	// filter 只取同一状态文件；length 是文件数，不能当作已理解的函数数。
	console.log(`${label}：${entries.filter((entry) => entry.status === status).length}`);
}
// 默认重点列出需复核的文件；--files 才额外列完整清单，防止日常输出几千行。
for (const entry of entries.filter((entry) => showFiles || entry.status === "stale")) {
	// 制表符分隔，既可以直接阅读，也可以重定向成 TSV 文件继续筛选。
	console.log(`${entry.status}\t${entry.path}\t${entry.note}`);
}
// 使用非零退出码提醒流水线/调用者有变化待复核；尚未完成的 pending 则正常报告，不伪装成失败。
if (entries.some((entry) => entry.status === "stale")) process.exitCode = 1;
